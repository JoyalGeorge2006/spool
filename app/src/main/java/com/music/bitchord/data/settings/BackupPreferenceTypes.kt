    fun checked(values: Map<String, Any?>, existing: Map<String, *>): Map<String, Any?> =
        values.mapNotNull { (key, value) ->
            val expected = types[key] ?: existing[key]?.let(::typeOf) ?: return@mapNotNull null
            require(typeOf(value) == expected) { "Wrong type for setting $key" }
            require(value !is Float || value.isFinite()) { "Invalid number for setting $key" }
            key to value
        }.toMap()

    private fun typeOf(value: Any?): String? = when (value) {
        is Boolean -> "Boolean"
        is Int -> "Int"
        is Long -> "Long"
        is Float -> "Float"
        is String -> "String"
        is Set<*> -> if (value.all { it is String }) "StringSet" else null
        else -> null
    }
